// Captures the Devpost gallery screenshots from the live build:
// node scripts/screens.mjs https://hyunsikparker.github.io/scraps/ ../submission/screens
import { chromium } from '@playwright/test'

const [url, out] = process.argv.slice(2)
const browser = await chromium.launch({ channel: 'chrome' })
const desk = await browser.newPage({ viewport: { width: 1320, height: 940 }, deviceScaleFactor: 2 })
await desk.goto(url)
await desk.evaluate(() => localStorage.clear())
await desk.goto(url)
await desk.getByRole('button', { name: 'Show a made-up example week' }).click()
await desk.locator('.lever').waitFor()
await desk.screenshot({ path: `${out}/01-week.png` })
await desk.locator('.week').screenshot({ path: `${out}/02-lever.png` })
await desk.getByRole('combobox', { name: /^Food/ }).selectOption('cheese')
await desk.getByRole('button', { name: 'One slice more' }).click()
await desk.getByLabel('Leftovers not eaten').check()
await desk.locator('.log').screenshot({ path: `${out}/03-log.png` })
await desk.getByRole('button', { name: 'Water' }).click()
const chart = desk.locator('.chart-head')
const c1 = await chart.boundingBox()
const bars = await desk.locator('.bars').boundingBox()
await desk.screenshot({ path: `${out}/04-water.png`, clip: { x: c1.x - 16, y: c1.y - 16, width: c1.width + 32, height: bars.y + bars.height - c1.y + 70 } })
const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, colorScheme: 'dark' })
await phone.goto(url)
await phone.evaluate(() => localStorage.clear())
await phone.goto(url)
await phone.getByRole('button', { name: 'Show a made-up example week' }).click()
await phone.locator('.week').scrollIntoViewIfNeeded()
await phone.evaluate(() => window.scrollTo(0, document.querySelector('.week').getBoundingClientRect().top + window.scrollY - 10))
await phone.screenshot({ path: `${out}/05-phone.png` })
await browser.close()
console.log('saved')
